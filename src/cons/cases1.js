/* Практические кейсы, часть 1. Все ответы вычисляются из исходных данных кейса. */
export const f = (x, d = 0) => {
  const v = Math.round(x * 10 ** d) / 10 ** d;
  let [i, fr] = Math.abs(v).toFixed(d).split(".");
  i = i.replace(/\B(?=(\d{3})+(?!\d))/g, "\u00a0");
  return (v < 0 ? "−" : "") + i + (fr ? "," + fr : "");
};
const T = (title, cols, rows) => ({ title, cols, rows });

