/* 19 Отложенный налог в консолидации */
function c19() {
  const naBook = 4000, fv = 1000, rate = 0.15, cons = 5500, life = 10, urp = 200;
  const dtl0 = fv * rate, naFV = naBook + fv - dtl0, gw = cons - naFV, dtl1 = (fv - fv / life) * rate, dta = urp * rate;
  return {
    id: "c19", level: 3, title: "Отложенный налог в консолидации: «Кокан Кондитер»",
    topics: ["IAS 12", "ОНО на дооценку", "ОНА на URP"],
    story: [
      "1 января группа «Кокан Кондитер» купила 100% «Риштан Сахар» за " + f(cons) + " млн. Балансовые чистые активы «Риштана» — " + f(naBook) + ". Цех дороже балансовой на " + f(fv) + " (срок 10 лет); налоговая база цеха не меняется. Ставка налога — 15% у обеих компаний.",
      "В течение года материнская продала «Риштану» сырьё; на 31 декабря нереализованная прибыль в запасах «Риштана» — " + f(urp) + " млн."
    ],
    tables: [],
    steps: [
      { q: "ОНО на дооценку цеха на дату покупки?", a: dtl0, unit: "млн", sol: f(fv) + " × 15% = " + f(dtl0) + " млн." },
      { q: "Справедливая стоимость чистых активов с учётом ОНО?", a: naFV, unit: "млн", sol: f(naBook) + " + " + f(fv) + " − " + f(dtl0) + " = " + f(naFV) + " млн." },
      { q: "Гудвил?", a: gw, unit: "млн", sol: f(cons) + " − " + f(naFV) + " = " + f(gw) + " млн. Без учёта ОНО он был бы на " + f(dtl0) + " меньше." },
      { q: "ОНО по цеху на 31 декабря?", a: dtl1, unit: "млн", sol: "Остаток дооценки " + f(fv - fv / life) + " × 15% = " + f(dtl1) + " млн. Распущено " + f(dtl0 - dtl1) + " — доход по налогу." },
      { q: "ОНА на нереализованную прибыль?", a: dta, unit: "млн", sol: f(urp) + " × 15% (ставка покупателя) = " + f(dta) + " млн." },
      { q: "Итоговое влияние URP на прибыль группы после налога (со знаком)?", a: -urp + dta, unit: "млн", sol: "−" + f(urp) + " + " + f(dta) + " = " + f(-urp + dta) + " млн." },
      { q: "Итоговое влияние доп. амортизации цеха на прибыль после налога (со знаком)?", a: -(fv / life) * (1 - rate), unit: "млн", sol: "−" + f(fv / life) + " + " + f(fv / life * rate) + " = " + f(-(fv / life) * (1 - rate)) + " млн." }
    ]
  };
}

