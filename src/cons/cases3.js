/* 21 Полный ОПиУ с ассоциированной */
function c21() {
  const P = { rev: 30000, cos: 18000, opex: 5000, inv: 450, fin: 600, tax: 1200, oci: 200 }, divS = 300, divA = 100;
  const S = { rev: 12000, cos: 7000, opex: 2000, fin: 300, tax: 500, oci: 120 };
  const sProf = S.rev - S.cos - S.opex - S.fin - S.tax, aProf = 1600, ic = 2000, stock = 500, urp = stock * 0.2, fee = 240, dep = 50;
  const rev = P.rev + S.rev - ic - fee, cos = P.cos + S.cos - ic + urp, opex = P.opex + S.opex - fee + dep;
  const inv = P.inv - divS - divA, assoc = 0.25 * aProf, fin = P.fin + S.fin, tax = P.tax + S.tax;
  const profit = rev - cos - opex + inv + assoc - fin - tax, nci = 0.25 * (sProf - urp - dep);
  const oci = P.oci + S.oci, nciT = nci + 0.25 * S.oci;
  return {
    id: "c21", level: 3, title: "Консолидированный ОПиУ и ПСД группы «Наманган Текстиль»",
    topics: ["SPLOCI", "Ассоциированная", "Плата за управление", "NCI"],
    story: [
      "Материнская владеет 75% «Чуст Пахта» весь год и 25% ассоциированной «Поп Трикотаж».",
      "«Чуст» продал материнской пряжу на " + f(ic) + " млн с маржой 20%; у материнской осталось пряжи на " + f(stock) + ".",
      "Материнская выставила «Чусту» плату за управление " + f(fee) + " (в своей выручке; у «Чуста» — в операционных расходах).",
      "Доп. амортизация дооценки «Чуста» — " + f(dep) + " в год (операционные расходы). Прибыль «Поп Трикотаж» — " + f(aProf) + ".",
      "Доход от инвестиций материнской: дивиденды «Чуста» " + f(divS) + ", «Поп Трикотаж» " + f(divA) + ", внешние " + f(P.inv - divS - divA) + "."
    ],
    tables: [T("Отчёты о прибылях за год, млн", ["Статья", "Материнская", "Чуст Пахта"], [
      ["Выручка", f(P.rev), f(S.rev)], ["Себестоимость", "(" + f(P.cos) + ")", "(" + f(S.cos) + ")"], ["Операционные расходы", "(" + f(P.opex) + ")", "(" + f(S.opex) + ")"],
      ["Доход от инвестиций", f(P.inv), "—"], ["Финансовые расходы", "(" + f(P.fin) + ")", "(" + f(S.fin) + ")"], ["Налог", "(" + f(P.tax) + ")", "(" + f(S.tax) + ")"],
      ["Прибыль", f(P.rev - P.cos - P.opex + P.inv - P.fin - P.tax), f(sProf)], ["ПСД: переоценка зданий", f(P.oci), f(S.oci)]
    ])],
    steps: [
      { q: "Выручка группы?", a: rev, unit: "млн", sol: f(P.rev) + " + " + f(S.rev) + " − " + f(ic) + " − плата за управление " + f(fee) + " = " + f(rev) + " млн." },
      { q: "Себестоимость группы?", a: cos, unit: "млн", sol: f(P.cos) + " + " + f(S.cos) + " − " + f(ic) + " + URP " + f(urp) + " = " + f(cos) + " млн." },
      { q: "Операционные расходы группы?", a: opex, unit: "млн", sol: f(P.opex) + " + " + f(S.opex) + " − " + f(fee) + " + " + f(dep) + " = " + f(opex) + " млн." },
      { q: "Доля в прибыли ассоциированной?", a: assoc, unit: "млн", sol: "25% × " + f(aProf) + " = " + f(assoc) + " млн." },
      { q: "Прибыль группы за год?", a: profit, unit: "млн",
        sol: f(rev) + " − " + f(cos) + " − " + f(opex) + " + " + f(inv) + " + " + f(assoc) + " − " + f(fin) + " − " + f(tax) + " = " + f(profit) + " млн." },
      { q: "Прибыль, относящаяся к NCI?", a: nci, unit: "млн", sol: "25% × (" + f(sProf) + " − " + f(urp) + " − " + f(dep) + ") = " + f(nci, 1) + " млн." },
      { q: "Общий совокупный доход группы?", a: profit + oci, unit: "млн", sol: f(profit) + " + " + f(oci) + " = " + f(profit + oci) + " млн." },
      { q: "Общий совокупный доход, относящийся к NCI?", a: nciT, unit: "млн", sol: f(nci, 1) + " + 25% × " + f(S.oci) + " = " + f(nciT, 1) + " млн." }
    ]
  };
}

